// 홈 카테고리 버튼으로 들어가는 스페셜 페이지 데이터
// - 페이지 = SpecialPage 템플릿 1개 + 아래 데이터
// - sections type: rank | poster | collection (기존) + video | videoRank | channel
//   · poster/rank : 세로 포스터 (ContentCard)
//   · video       : 16:9 영상 카드 (VideoRow → VideoSlider + movie-videos__card)
//   · videoRank   : 16:9 영상 카드 + 순위
//   · channel     : 채널 로고 박스
// - filters: 영화+ · 뉴스 · 골프 탭 (CategoryPage 필터 스타일)
//   · sections: 탭을 누르면 해당 섹션만 표시
//   · items   : 탭을 누르면 해당 콘텐츠 그리드(CollectionRow) 표시
// - 콘텐츠는 2026-11-05 기준 웨이브(wavve.com) 각 스페셜 페이지 구성을 따른다.
//   이미지는 웨이브 이미지 서버(image.wavve.com) 외부 URL을 그대로 사용한다.

const WAVVE_IMAGE = 'https://image.wavve.com/v1/thumbnails/';

// 웨이브 이미지 경로 (yyyymm/숫자ID 형태는 meta/image 경로)
const wavveImage = (size, path) => {
  if (!path) return '';
  const meta = /^\d{6}\/\d{13,}\./.test(path) ? 'meta/image/' : '';
  return `${WAVVE_IMAGE}${size}/${meta}${path}`;
};

// 스페셜 페이지 hero 이미지 (public/images/special-hero/{이름}_hero.jpg · {이름}_logo.png)
// - short: 골프 · 뉴스처럼 낮은 배경(1920×380) + 왼쪽 로고 헤더 (웨이브 short-header)
// - tag  : 로고 위 작은 태그 이미지 (웨이브 w-special-title-tag-box)
const heroPath = (file) => `${import.meta.env.BASE_URL}images/special-hero/${file}`;
const hero = (name, options = {}) => ({
  background: heroPath(`${name}_hero.jpg`),
  logo: heroPath(`${name}_logo.png`),
  ...options,
});

// 콘텐츠 클릭 → /open 에서 TMDB id 를 찾아 상세 페이지로 이동 (pages/special/TmdbOpen.jsx)
// kind: 'movie' 영화만 검색 | 'multi' 영화 · 시리즈 함께 검색
const openLink = (title, kind = 'multi') => `/open?${new URLSearchParams({ title, kind })}`;

// 영화 섹션 키 (영화+ 전체 · 독점 영화 · CJ ENM 영화) → 영화로 검색
const isMovieKey = (key) => key.startsWith('movie-') || key.endsWith('-movie');

// 세로 포스터: [제목, 이미지, 표시]  표시 = '새로운' | '개별구매' | 'original' | 'exclusive'
const posters = (key, list) =>
  list.map(([title, path, flag = ''], index) => ({
    id: `${key}-${index}`,
    title,
    poster: wavveImage('480_720', path),
    badge: flag === '새로운' || flag === '개별구매' ? flag : '',
    isOriginal: flag === 'original' || flag === 'exclusive',
    link: openLink(title, isMovieKey(key) ? 'movie' : 'multi'),
  }));

// 골프 · 뉴스 클립은 TMDB 작품이 없어 라이브 페이지로 연결
const isLiveClipKey = (key) => key.startsWith('golf-') || key.startsWith('news-') || key === 'kbs-news24';

// 16:9 영상: [제목, 이미지, 설명, 날짜, 배지, 재생시간]
// link 를 주지 않으면 영상 제목으로 상세 페이지 연결 (라이브는 '/live')
const videos = (key, list, size = '480_270', link = null) =>
  list.map(([title, path, desc = '', date = '', badge = '', duration = ''], index) => ({
    id: `${key}-${index}`,
    title,
    image: wavveImage(size, path),
    desc,
    date,
    badge,
    duration,
    link: link ?? (isLiveClipKey(key) ? '/live' : openLink(title)),
  }));

// 회차 · 클립 영상은 프로그램 상세 페이지로 연결
const forProgram = (items, program) => items.map((item) => ({ ...item, link: openLink(program) }));


