const posterFields = ['kind', 'tmdbId', 'tmdbTitle', 'tmdbYear', 'tmdbSeason',
  'isPlaceholder', 'tmdbMatchStatus', 'tmdbSource'];

// id/title/genre/days/badge/isOriginal/link 등 페이지 고유 필드는 보존한다.
export const withContent = (item, scope) => {
  const contentId = item.contentId || contentReferences[scope + ':' + item.id];
  const shared = contentCatalog[contentId];
  if (!shared) return item;
  const posterData = Object.fromEntries(posterFields
    .filter((field) => Object.hasOwn(shared, field)).map((field) => [field, shared[field]]));
  const result = { ...item, ...posterData, contentId };
  if (shared.tmdbId || shared.poster || shared.image) result.isPlaceholder = false;
  // 공통 이미지가 지정되지 않았다면 기존 페이지의 정상 이미지를 유지한다.
  if (shared.poster || shared.image) {
    result.poster = shared.poster || shared.image;
    result.image = shared.image || '';
  }
  return result;
};

// 같은 작품은 표시용 별칭이 달라도 동일한 검색어/캐시 키를 사용한다.
export const getContentPosterItem = (item) => {
  const shared = contentCatalog[item.contentId];
  return shared ? { ...withContent(item), title: shared.title } : item;
};
