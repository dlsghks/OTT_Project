/* =========================
   프로그램 상세 (/golf/program/:programId)
========================= */
export const getGolfProgram = (programId) => {
  const row = programRows[programId];
  if (!row) return null;

  const [title, poster, backdrop, overview] = row;
  const latest = latestRows[programId];

  // 회차 · 클립: 최신 영상 + 이 프로그램의 클립 (클립 재생 화면으로 연결)
  const latestClip = latest && !getGolfClip(programId) && {
    id: programId,
    title: latest[1],
    image: wavveImage('480_270', latest[2]),
    poster: wavveImage('814_458', latest[2]),
    programId,
    program: title,
    source: sourceOf(programId, programId),
    category: '최신 영상',
    date: `${latest[3]}(${latest[4]})`,
    duration: formatPlayTime(latest[5]),
    badge: '',
    desc: title,
    link: golfClipLink(programId),
  };
  const clips = allClips.filter((clip) => clip.programId === programId);

  return {
    id: programId,
    title,
    poster: wavveImage('480_720', poster),
    backdrop: wavveImage('0_0', backdrop),
    overview,
    tour: programId.startsWith('S31_') || programId.startsWith('C3541_') ? '웨이브 단독 중계' : '골프',
    episodes: [latestClip, ...clips].filter(Boolean),
  };
};

// 프로그램 최신 영상도 클립 재생 화면에서 재생 (프로그램 id 로 찾기)
export const getGolfClipOrLatest = (clipId) =>
  getGolfClip(clipId) ?? getGolfProgram(clipId)?.episodes.find((item) => item.id === clipId) ?? null;
