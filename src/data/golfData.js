export const getGolfClip = (clipId) => allClips.find((clip) => clip.id === clipId);

// 클립 재생 화면 오른쪽 추천 영상: 같은 대회 클립 → 같은 분류 클립 순서
export const getGolfClipRecommends = (clip) => {
  const others = allClips.filter((item) => item.id !== clip.id);
  const sameProgram = others.filter((item) => item.programId === clip.programId);
  const sameCategory = others.filter((item) => item.programId !== clip.programId && item.category === clip.category);
  const list = [...sameProgram, ...sameCategory];

  // 클립이 없는 프로그램(골프의 모든 것 등)의 최신 영상 → 다른 프로그램 최신 영상
  if (!list.length) {
    return Object.keys(latestRows)
      .filter((programId) => programId !== clip.programId)
      .map((programId) => getGolfProgram(programId).episodes[0])
      .filter((item) => item && item.category === clip.category)
      .slice(0, 20);
  }
  return list.slice(0, 20);
};

