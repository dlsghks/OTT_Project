const toClip = ([id, title, image, programId, date, weekday, playTime, clipType]) => ({
  id,
  title,
  image: wavveImage('480_270', image),
  poster: wavveImage('814_458', image),
  programId,
  program: programTitle(programId),
  source: sourceOf(id, programId),
  category: CLIP_TYPES[clipType] ?? '다시보기',
  date: `${date}(${weekday})`,
  duration: formatPlayTime(playTime),
  badge: '무료',
  desc: CLIP_TYPES[clipType] ?? programTitle(programId),
  link: golfClipLink(id),
});

